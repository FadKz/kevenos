const {test} = require('node:test');
const assert = require('node:assert/strict');
const {readFileSync} = require('node:fs');
const {JSDOM} = require('jsdom');

test('one sheet handles questions and important messages without interrupting notes',async t=>{
  const html=readFileSync('static/participant.html','utf8');
  const dom=new JSDOM(html,{url:'https://pitch.test/participant',runScripts:'outside-only',pretendToBeVisual:true});
  const w=dom.window;
  t.after(()=>w.close());
  const $=id=>w.document.getElementById(id);
  $('guide').hidden=false;
  w.KEV={};
  w.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
  w.HTMLDialogElement.prototype.close=function(){this.open=false;this.dispatchEvent(new w.Event('close'));};
  w.eval(readFileSync('static/participant-messages.js','utf8'));
  const base={message_scope:'test',action:{code:'program'},messages:[]};
  const dialog=$('participant-message-sheet');
  const inbox=$('participant-messages-button');
  const input=w.document.createElement('textarea');
  w.document.body.append(input);
  input.focus();
  w.KEV.messages.receive(base);
  const quiz={id:'quiz:1',title:'First question',label:'Quiz question',state:'open',auto:true,root:'event-quiz-player'};
  w.KEV.messages.replace('quiz',[quiz]);
  assert.equal(dialog.open,false);
  assert.equal(inbox.textContent,'Messages · 1');
  inbox.click();
  dialog.querySelector('[data-message-list] button').click();
  assert.equal(dialog.querySelector('[data-message-detail]').firstElementChild.id,'event-quiz-player');
  dialog.close();
  input.blur();
  w.KEV.messages.replace('quiz',[quiz]);
  assert.equal(dialog.open,false);
  w.KEV.messages.receive({...base,announcement:{updated_at:4},messages:[{id:'a',text:'<b>Return to your seats</b>',important:true,updated_at:4}]});
  assert.equal(dialog.open,true);
  assert.match(dialog.querySelector('[data-message-detail]').textContent,/Return to your seats/);
  assert.equal(dialog.querySelector('[data-message-detail] b'),null);
  dialog.close();
  w.KEV.messages.clear();
  assert.equal(inbox.textContent,'Messages');
});
